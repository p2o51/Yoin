#!/usr/bin/env python3
"""Writes lib/data/search/search_nfkd.dart: Unicode NFKD of every single code point that changes under it.

Search folding (lib/data/search/search_match.dart, :shared SearchMatch.kt) normalises one code point at a time
(Android: java.text.Normalizer, iOS: Foundation); Dart has no normaliser, so the decompositions are a table.
Hangul syllables are left out: folding keeps them whole. Run from harmony/:

    python3 scripts/gen_search_nfkd.py

The Unicode version is Python's (unicodedata.unidata_version), written into the file.
"""

import sys
import unicodedata
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "lib" / "data" / "search" / "search_nfkd.dart"


def main() -> None:
    entries = []
    for cp in range(0x110000):
        if 0xD800 <= cp <= 0xDFFF or 0xAC00 <= cp <= 0xD7A3:
            continue
        ch = chr(cp)
        nfkd = unicodedata.normalize("NFKD", ch)
        if nfkd != ch:
            entries.append("%x:%s" % (cp, ".".join("%x" % ord(c) for c in nfkd)))
    # Dart string literals of at most ~100 chars per line, joined with ';'.
    data = ";".join(entries)
    lines = [data[i : i + 100] for i in range(0, len(data), 100)]
    body = "\n".join("    '%s'" % line for line in lines)
    OUT.write_text(
        "// GENERATED by scripts/gen_search_nfkd.py (Unicode %s). Do not edit.\n"
        "//\n"
        "// Unicode NFKD of each single code point that changes under it, Hangul syllables left out:\n"
        "// `codepoint:decomposition` in hex, code points of the decomposition joined by '.', entries by ';'.\n"
        "library;\n\n"
        "const String searchNfkdData =\n%s;\n" % (unicodedata.unidata_version, body),
        encoding="utf-8",
    )
    print("%d entries -> %s" % (len(entries), OUT), file=sys.stderr)


if __name__ == "__main__":
    main()
