package com.gpo.yoin.data.sync.backup

import java.io.ByteArrayOutputStream
import java.io.File
import java.time.ZoneId
import java.time.ZoneOffset
import kotlinx.coroutines.test.runTest
import kotlinx.serialization.json.Json
import kotlinx.serialization.json.JsonElement
import kotlinx.serialization.json.JsonObject
import kotlinx.serialization.json.JsonPrimitive
import org.junit.After
import org.junit.Assert.assertEquals
import org.junit.Test
import org.junit.runner.RunWith
import org.robolectric.RobolectricTestRunner

/**
 * Pins every byte an export writes (manifest, snapshot, readable Markdown) for fixed data, so moving the
 * backup core into :shared can be shown to change nothing. The expected text was generated by the
 * pre-move app code (commit "test: pin backup export bytes") and must never be regenerated to make a
 * refactor pass. Regenerate only for an intended format change:
 * `YOIN_WRITE_BACKUP_PIN=1 ./gradlew :app:testDebugUnitTest --tests '*BackupExportPinTest*'`.
 *
 * Zip containers aren't compared byte for byte (ZipOutputStream stamps entry times); their entries are.
 */
@RunWith(RobolectricTestRunner::class)
class BackupExportPinTest {
    private val phone = BackupTestDevice()

    @After
    fun tearDown() = phone.close()

    @Test
    fun should_writeTheSameEntries_when_exportingAFixedSnapshot() = runTest {
        val cases = linkedMapOf<String, JsonElement>()
        for ((name, labels, zone) in listOf(
            Triple("en-UTC", ReadableLabels.English, ZoneOffset.UTC as ZoneId),
            Triple("zh-Shanghai", ReadableLabels.Chinese, ZoneId.of("Asia/Shanghai")),
            Triple("en-NewYork", ReadableLabels.English, ZoneId.of("America/New_York")),
        )) {
            val out = ByteArrayOutputStream()
            val summary = BackupWriter(PinFixture.names, labels, zone).write(PinFixture.content(), PinFixture.source, out)
            cases[name] = JsonObject(
                mapOf(
                    "readableFiles" to JsonPrimitive(summary.readableFiles),
                    "entries" to JsonObject(BackupTestDevice.entries(out.toByteArray()).mapValues { JsonPrimitive(it.value) }),
                ),
            )
        }
        assertPinned("fixed-snapshot", JsonObject(cases))
    }

    @Test
    fun should_writeTheSameEntries_when_exportingASeededDevice() = runTest {
        val p = phone.addSubsonic("p1", "https://music.example.com", "alice")
        phone.note(p, "n1", "t1", "first listen, rain outside", at = 2_000)
        phone.rate(p, "t1", 9f, at = 2_100)
        phone.rate(p, "t2", 7.5f, at = 2_200)
        phone.albumRating(p, "al1", 8f, "A long review.", at = 2_300)
        phone.albumNote(p, "an1", "al1", "album note text", at = 2_400)
        phone.albumTitle(p, "al1", "My Rainy Album", at = 2_500)
        phone.memory(p, "al1", "AI copy", "AI Title", at = 2_600)
        phone.link(p, "t1", "al1", at = 2_700)
        phone.played(p, "t2", "Second Song", "al1", "Rain Album", at = 2_800)
        phone.addProfile("apple", "applemusic", "Apple", createdAt = 3_000)
        phone.rate("apple", "1440857781", 6f, at = 3_100, provider = "applemusic")

        val (zip, summary) = phone.exportZip()
        assertPinned(
            "seeded-device",
            JsonObject(
                mapOf(
                    "readableFiles" to JsonPrimitive(summary.readableFiles),
                    "entries" to JsonObject(BackupTestDevice.entries(zip).mapValues { JsonPrimitive(it.value) }),
                ),
            ),
        )
    }

    private fun assertPinned(name: String, actual: JsonElement) {
        val text = PRETTY.encodeToString(JsonElement.serializer(), actual) + "\n"
        val file = File(pinDir(), "$name.json")
        if (System.getenv("YOIN_WRITE_BACKUP_PIN") == "1" || !file.exists()) {
            file.parentFile?.mkdirs()
            file.writeText(text)
        }
        assertEquals(file.readText(), text)
    }

    private fun pinDir(): File {
        val root = generateSequence(File("").absoluteFile) { it.parentFile }
            .first { File(it, "app").isDirectory && File(it, "settings.gradle.kts").isFile }
        return File(root, "app/src/test/resources/backup-pin")
    }

    private companion object {
        val PRETTY = Json { prettyPrint = true }
    }
}
