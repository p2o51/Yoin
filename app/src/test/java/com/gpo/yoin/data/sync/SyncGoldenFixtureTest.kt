    private fun gunzip(bytes: ByteArray): String =
        GZIPInputStream(ByteArrayInputStream(bytes)).use { it.readBytes() }.toString(Charsets.UTF_8)

    private fun obj(vararg pairs: Pair<String, Any?>): JsonObject = JsonObject(
        linkedMapOf(
            *pairs.map { (k, v) ->
                k to when (v) {
                    null -> JsonNull
                    is JsonElement -> v
                    is String -> JsonPrimitive(v)
                    is Number -> JsonPrimitive(v)
                    is Boolean -> JsonPrimitive(v)
                    else -> error("unsupported $v")
                }
            }.toTypedArray(),
        ),
    )

    /** Two-space JSON with one key per line, stable across kotlinx versions (no prettyPrint config). */
    private fun pretty(element: JsonElement, indent: String = ""): String = when (element) {
        is JsonObject -> if (element.isEmpty()) {
            "{}"
        } else {
            element.entries.joinToString(",\n", "{\n", "\n$indent}") { (k, v) ->
                "$indent  ${JsonPrimitive(k)}: ${pretty(v, "$indent  ")}"
            }
        }
        is JsonArray -> if (element.isEmpty()) {
            "[]"
        } else {
            element.joinToString(",\n", "[\n", "\n$indent]") { "$indent  ${pretty(it, "$indent  ")}" }
        }
        else -> element.toString()
    }

    private fun kotlinMirror(text: String): String = buildString {
        append("// Generated by app/src/test/java/com/gpo/yoin/data/sync/SyncGoldenFixtureTest.kt. Do not edit.\n")
        append("package com.gpo.yoin.shared.sync.golden\n\n")
        append("/** iosApp/YoinTests/Fixtures/sync-golden.json, as Android's sync wrote it. */\n")
        append("internal val ANDROID_SYNC_GOLDEN: String = listOf(\n")
        text.chunked(1500).forEach { chunk -> append("    \"").append(escape(chunk)).append("\",\n") }
        append(").joinToString(\"\")\n")
    }

    private fun escape(s: String): String = buildString {
        for (c in s) {
            when {
                c == '\\' -> append("\\\\")
                c == '"' -> append("\\\"")
                c == '$' -> append("\\$")
                c == '\n' -> append("\\n")
                c == '\r' -> append("\\r")
                c == '\t' -> append("\\t")
                c.code < 0x20 || c.code > 0x7e -> append("\\u").append("%04x".format(c.code))
                else -> append(c)
            }
        }
    }

