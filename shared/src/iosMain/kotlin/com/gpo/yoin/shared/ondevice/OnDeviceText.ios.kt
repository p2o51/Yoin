/**
 * Kotlin/Native's Unicode table for the Basic Multilingual Plane; above it (where Kotlin has no code point
 * category) the supplementary blocks Unicode files as So: ancient, musical, Mahjong / domino / cards, emoji and
 * pictographs, legacy computing. The golden vectors pin the cases a greeting meets.
 */
internal actual fun isOtherSymbolCodePoint(codePoint: Int): Boolean {
    if (codePoint < 0x10000) return codePoint.toChar().category == CharCategory.OTHER_SYMBOL
    return SupplementarySymbols.any { codePoint in it }
}

