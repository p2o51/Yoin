package com.gpo.yoin.shared.share

import java.io.File
import kotlin.test.Test
import kotlin.test.assertEquals

/**
 * Writes and checks the share-card golden vectors (shared/src/commonTest/resources/golden/share-cards.json) that
 * iOS (Swift through YoinShared) and HarmonyOS (the Dart port) are tested against, and the same file as a Kotlin
 * string (commonTest ShareCardsGoldenData.kt) for [ShareCardsGoldenReplayTest] on the iOS simulator. Every
 * expected value is what this Kotlin computes through [YoinShareCards]; Android's app pins the same file (app
 * ShareCardsPinTest). Regenerate after an intentional change:
 * `YOIN_WRITE_SHARE_CARDS_GOLDEN=1 ./gradlew :shared:testAndroidHostTest --tests '*ShareCardsGoldenTest*'`.
 */
class ShareCardsGoldenTest {

    @Test
    fun should_matchCheckedInGolden_when_kotlinComputesEveryVector() {
        val json = ShareCardsGolden.render()
        val file = File(root(), ShareCardsGolden.FILE)
        val mirror = File(root(), MIRROR)
        if (System.getenv("YOIN_WRITE_SHARE_CARDS_GOLDEN") == "1" || !file.exists() || !mirror.exists()) {
            file.parentFile?.mkdirs()
            file.writeText(json)
            mirror.writeText(kotlinMirror(json))
        }
        assertEquals(file.readText(), json)
        assertEquals(mirror.readText(), kotlinMirror(json))
    }

    private fun root(): File = generateSequence(File("").absoluteFile) { it.parentFile }
        .first { File(it, "shared").isDirectory && File(it, "settings.gradle.kts").isFile }

    /** The file as a Kotlin string, one literal per line (each well under the JVM's 64 KB constant). */
    private fun kotlinMirror(json: String): String = buildString {
        append("// Generated by ShareCardsGoldenTest (androidHostTest) from ").append(ShareCardsGolden.FILE).append(". Do not edit.\n")
        append("package com.gpo.yoin.shared.share\n\n")
        append("internal val SHARE_CARDS_GOLDEN: String = listOf(\n")
        json.lineSequence().filter(String::isNotEmpty).forEach { line ->
            append("    \"").append(escape(line)).append("\\n\",\n")
        }
        append(").joinToString(\"\")\n")
    }

    private fun escape(line: String): String = buildString {
        line.forEach { c ->
            when (c) {
                '\\' -> append("\\\\")
                '"' -> append("\\\"")
                '$' -> append("\\$")
                else -> append(c)
            }
        }
    }

    private companion object {
        const val MIRROR = "shared/src/commonTest/kotlin/com/gpo/yoin/shared/share/ShareCardsGoldenData.kt"
    }
}
