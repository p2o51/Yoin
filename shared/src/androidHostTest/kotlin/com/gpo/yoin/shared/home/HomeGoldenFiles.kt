package com.gpo.yoin.shared.home

import java.io.File
import kotlin.test.assertEquals

/**
 * Writes and checks one Home golden file and its Kotlin mirror (the file as a string, for the iOS simulator's
 * replay), the way AlbumAboutGoldenTest does: written when [env] is `1` or either file is missing, else
 * compared byte for byte.
 */
internal object HomeGoldenFiles {

    fun check(json: String, file: String, mirror: String, constant: String, env: String, writer: String) {
        val root = generateSequence(File("").absoluteFile) { it.parentFile }
            .first { File(it, "shared").isDirectory && File(it, "settings.gradle.kts").isFile }
        val out = File(root, file)
        val kotlin = File(root, mirror)
        val text = kotlinMirror(json, file, constant, writer)
        if (System.getenv(env) == "1" || !out.exists() || !kotlin.exists()) {
            out.parentFile?.mkdirs()
            out.writeText(json)
            kotlin.writeText(text)
        }
        assertEquals(out.readText(), json, "$file is stale: regenerate with $env=1")
        assertEquals(kotlin.readText(), text, "$mirror is stale: regenerate with $env=1")
    }

    /** The file as a Kotlin string, one literal per line (each well under the JVM's 64 KB constant). */
    private fun kotlinMirror(json: String, file: String, constant: String, writer: String): String = buildString {
        append("// Generated by ").append(writer).append(" (androidHostTest) from ").append(file).append(". Do not edit.\n")
        append("package com.gpo.yoin.shared.home\n\n")
        append("internal val ").append(constant).append(": String = listOf(\n")
        json.lineSequence().filter(String::isNotEmpty).forEach { line ->
            append("    \"").append(escape(line)).append("\\n\",\n")
        }
        append(").joinToString(\"\")\n")
    }

    private fun escape(line: String): String = buildString {
        line.forEach { c ->
            when (c) {
                '\\' -> append("\\\\")
                '"' -> append("\\\"")
                '$' -> append("\\$")
                else -> append(c)
            }
        }
    }
}
