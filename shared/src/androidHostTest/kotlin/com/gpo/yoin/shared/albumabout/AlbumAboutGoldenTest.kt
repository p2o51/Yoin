package com.gpo.yoin.shared.albumabout

import java.io.File
import kotlin.test.Test
import kotlin.test.assertEquals

/**
 * Writes and checks the album About golden vectors (shared/src/commonTest/resources/golden/album-about.json)
 * that iOS (Swift through YoinShared) and HarmonyOS (the Dart port) are tested against, and the same file as
 * a Kotlin string (commonTest AlbumAboutGoldenData.kt) for [AlbumAboutGoldenReplayTest] on the iOS simulator.
 * Every expected value is what this Kotlin computes through [YoinAlbumAbout]; Android's app pins the same file
 * (app AlbumAboutPinTest). Regenerate after an intentional change:
 * `YOIN_WRITE_ALBUM_ABOUT_GOLDEN=1 ./gradlew :shared:testAndroidHostTest --tests '*AlbumAboutGoldenTest*'`.
 */
class AlbumAboutGoldenTest {

    @Test
    fun should_matchCheckedInGolden_when_kotlinComputesEveryVector() {
        val json = AlbumAboutGolden.render()
        val file = File(root(), AlbumAboutGolden.FILE)
        val mirror = File(root(), MIRROR)
        if (System.getenv("YOIN_WRITE_ALBUM_ABOUT_GOLDEN") == "1" || !file.exists() || !mirror.exists()) {
            file.parentFile?.mkdirs()
            file.writeText(json)
            mirror.writeText(kotlinMirror(json))
        }
        assertEquals(file.readText(), json)
        assertEquals(mirror.readText(), kotlinMirror(json))
    }

    private fun root(): File = generateSequence(File("").absoluteFile) { it.parentFile }
        .first { File(it, "shared").isDirectory && File(it, "settings.gradle.kts").isFile }

    /** The file as a Kotlin string, one literal per line (each well under the JVM's 64 KB constant). */
    private fun kotlinMirror(json: String): String = buildString {
        append("// Generated by AlbumAboutGoldenTest (androidHostTest) from ").append(AlbumAboutGolden.FILE).append(". Do not edit.\n")
        append("package com.gpo.yoin.shared.albumabout\n\n")
        append("internal val ALBUM_ABOUT_GOLDEN: String = listOf(\n")
        json.lineSequence().filter(String::isNotEmpty).forEach { line ->
            append("    \"").append(escape(line)).append("\\n\",\n")
        }
        append(").joinToString(\"\")\n")
    }

    private fun escape(line: String): String = buildString {
        line.forEach { c ->
            when (c) {
                '\\' -> append("\\\\")
                '"' -> append("\\\"")
                '$' -> append("\\$")
                else -> append(c)
            }
        }
    }

    private companion object {
        const val MIRROR = "shared/src/commonTest/kotlin/com/gpo/yoin/shared/albumabout/AlbumAboutGoldenData.kt"
    }
}
