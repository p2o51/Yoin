            for (s in accounts) for (t in accounts) for (r in refs) {
                if (r.provider == t.provider) add(obj("source" to str(s.scope), "target" to str(t.scope), "ref" to str(r.toString()), "compatible" to JsonPrimitive(TransferRules.compatible(s, t, r))))
            }
        }
        val migration = listOf(Triple("s-a", "n1", "s-b"), Triple("s-a", "n1", "s-c"), Triple("local-p1", "3f2c-uuid", "s-x"), Triple("s-晴天", "笔记", "a-1"))
            .map { (a, b, c) -> obj("srcScope" to str(a), "srcId" to str(b), "dstScope" to str(c), "id" to str(MigrationIds.derive(a, b, c))) }
