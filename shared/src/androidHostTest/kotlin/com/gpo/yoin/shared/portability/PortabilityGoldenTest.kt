    private val alice = BackupTestDevice.scopeOf("https://music.example.com", "alice")

    /**
     * The backup every import case reads: a phone's export (real adapter payloads) plus records for the rules
     * a phone wouldn't produce by itself: a tombstone, an unknown kind, a newer kind version, an unknown payload
     * key, and two accounts only in the cloud (one of them purged on the tablet).
     */
    private suspend fun importBackup(): ParsedBackup {
        val phone = BackupTestDevice("dev-phone", "Pixel 9")
        val p = phone.addSubsonic("p1", "https://music.example.com", "alice")
        phone.note(p, "n1", "t1", "first listen", at = 2_000)
        phone.note(p, "n2", "t2", "second", at = 2_050)
        phone.rate(p, "t1", 9.0, at = 2_100)
        phone.rate(p, "t2", 6.0, at = 2_150)
        phone.albumRating(p, "al1", 8.0, "Backup review.", at = 2_300)
        phone.albumRating(p, "al2", 7.0, "Backup review 2.", at = 2_300)
        phone.albumNote(p, "an1", "al1", "album note", at = 2_400)
        phone.domain.putAlbumTitle(p, AlbumTitleRow("subsonic", "al1", "My Title", 2_500))
        phone.domain.putMemoryCopy(p, MemoryCopyRow("subsonic", "album", "al1", "AI copy", "ph", 2_600, "AI Title", "th"))
        phone.link(p, "t1", "al1", at = 2_700)
        phone.addProfile("p9", "applemusic", "Apple")
        phone.rate("p9", "1440", 7.0, at = 2_200, provider = "applemusic")
        val content = SnapshotAssembler(phone.adapters, null, phone.backupDomain, "dev-phone", "Pixel 9", 28)
            .build(phone.domain.profiles(), 1_795_400_000_000)
        val scope = content.accounts.first().scope
        val extra = SyncJson.decodeFromString(
            SyncEnvelope.serializer(),
            ImportExtras.RECORDS.replace("SCOPE", scope),
        ).records
        val records = content.snapshot.records.map { record ->
            if (record.kind == "song_note" && record.key == "n1") {
                record.copy(payload = JsonObject(record.payload!! + ("mood" to Json.parseToJsonElement("""{"kept":true}"""))))
            } else {
                record
            }
        } + extra
        val snapshot = content.snapshot.copy(records = records.sortedWith(compareBy({ it.kind }, { it.scope }, { it.key })))
        val accounts = content.accounts + listOf(
            BackupAccount(scope = "s-cloud", provider = "spotify", displayName = "Carol", onDevice = false),
            BackupAccount(scope = "s-gone", provider = "spotify", displayName = "Gone", onDevice = false),
        )
        val files = BackupExport.files(
            BackupContent(snapshot, accounts, content.localProfiles, emptyList()),
            BackupSource(BackupFormat.LOCATION_GOOGLE_DRIVE, "dev-phone", "Pixel 9", "0.6.3", 28),
            ReadableNames.None,
            ReadableLabels.English,
            "UTC",
        )
        return BackupParser.parse(files.manifestBytes, files.snapshotBytes, files.readable.size)
    }

