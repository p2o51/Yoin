/**
 * The golden vectors other ports of the backup / import / transfer core are tested against (HarmonyOS's
 * Dart port, and the Swift wrappers): every expected value is what this Kotlin computes, and the test fails
 * when a checked-in file drifts from it. Files under shared/src/commonTest/resources/golden/:
 *
 *  - backup-export.json   snapshot + accounts + names -> manifest / snapshot text / readable Markdown files.
 *                         Its three cases are the input Android's BackupExportPinTest pins, and the expected
 *                         entries are checked against that pin (app/src/test/resources/backup-pin/).
 *  - backup-import.json   a backup + a device (profiles, rows, replica) + choices -> plan, result, rows after.
 *  - memories-transfer.json  id-space, migration-id, mention and review vectors, plus applier cases:
 *                         items + picks + ledger + target rows -> result, ledger entries, target rows after.
 *
 * Regenerate after an intentional change:
 * `YOIN_WRITE_PORTABILITY_GOLDEN=1 ./gradlew :shared:testAndroidHostTest --tests '*PortabilityGoldenTest*'`.
 */
class PortabilityGoldenTest {
    private val pretty = Json {
        prettyPrint = true
        prettyPrintIndent = "  "
    }

    @Test
    fun should_matchCheckedInExportGolden_andAndroidsPinnedEntries() = runBlocking {
        val golden = exportGolden()
        check("backup-export.json", golden)
        // Android's pinned export (generated by the pre-move app code) is the same bytes.
        val pin = repoFile("app/src/test/resources/backup-pin/fixed-snapshot.json")
        if (pin.exists()) {
            val pinned = Json.parseToJsonElement(pin.readText()).jsonObject
            for (case in (golden["cases"] as JsonArray).map { it.jsonObject }) {
                val name = (case["name"] as JsonPrimitive).content
                val expected = case["expected"]!!.jsonObject
                val entries = pinned.getValue(name).jsonObject.getValue("entries").jsonObject
                assertEquals(entries.getValue(BackupFormat.MANIFEST_PATH), expected.getValue("manifestJson"), name)
                assertEquals(entries.getValue(BackupFormat.SNAPSHOT_PATH), expected.getValue("snapshotJson"), name)
                val readable = (expected.getValue("readable") as JsonArray).map { it.jsonObject }
                assertEquals(
                    entries.keys.filter { it.startsWith(BackupFormat.READABLE_DIR) },
                    readable.map { (it.getValue("path") as JsonPrimitive).content },
                    name,
                )
                readable.forEach { assertEquals(entries.getValue((it.getValue("path") as JsonPrimitive).content), it.getValue("text"), name) }
            }
        }
    }

    @Test
    fun should_matchCheckedInImportGolden() = runBlocking { check("backup-import.json", importGolden()) }

    @Test
    fun should_matchCheckedInTransferGolden() = runBlocking { check("memories-transfer.json", transferGolden()) }

    private fun check(name: String, golden: JsonObject) {
        val text = pretty.encodeToString(JsonElement.serializer(), golden) + "\n"
        val file = repoFile("shared/src/commonTest/resources/golden/$name")
        if (System.getenv("YOIN_WRITE_PORTABILITY_GOLDEN") == "1" || !file.exists()) {
            file.parentFile?.mkdirs()
            file.writeText(text)
        }
        assertEquals(file.readText(), text, name)
    }

    private fun repoFile(path: String): File {
        val root = generateSequence(File("").absoluteFile) { it.parentFile }
            .first { File(it, "shared").isDirectory && File(it, "settings.gradle.kts").isFile }
        return File(root, path)
    }

