    private suspend fun importGolden(): JsonObject {
        val backup = importBackup()
        val cases = importCases.map { case ->
            val device = BackupTestDevice("dev-tablet", "Pixel Tablet")
            device.domain.profileList += case.profiles
            case.seed(device)
            if (case.replica) case.seedReplica(device.store)
            val before = domainJson(device)
            val replica = if (case.replica) StoreBackupReplica(device.store, device.engine(now = 50_000)) else null
            val plan = ImportPlanner.plan(backup, device.domain.profiles(), replica)
            val result = device.merger().apply(plan, case.choices, device.domain.profiles(), replica, importGlobal = true)
            val second = if (case.applyTwice) {
                device.merger().apply(ImportPlanner.plan(backup, device.domain.profiles(), replica), case.choices, device.domain.profiles(), replica, true)
            } else {
                null
            }
            obj(
                "name" to str(case.name),
                "input" to obj(
                    "profiles" to arr(case.profiles.map(::profileJson)),
                    "domain" to before,
                    "replica" to if (case.replica) replicaJson(device.store) else JsonNull,
                    "choices" to obj(*case.choices.map { (scope, target) -> scope to targetJson(target) }.toTypedArray()),
                    "importGlobal" to JsonPrimitive(true),
                    "applyTwice" to JsonPrimitive(case.applyTwice),
                ),
                "expected" to obj(
                    "plan" to planJson(plan),
                    "result" to resultJson(result),
                    "secondResult" to (second?.let(::resultJson) ?: JsonNull),
                    "domain" to domainJson(device),
                    "replicaRecords" to if (case.replica) {
                        arr(device.store.allRecords().sortedWith(compareBy({ it.kind }, { it.scope }, { it.key })).map { obj("kind" to str(it.kind), "scope" to str(it.scope), "key" to str(it.key), "ts" to num(it.ts), "device" to str(it.device), "payload" to str(it.payload)) })
                    } else {
                        JsonNull
                    },
                ),
            )
        }
        return obj(
            "about" to str(
                "Golden vectors for backup import (plan + merge), generated from :shared Kotlin by PortabilityGoldenTest " +
                    "(androidHostTest). Do not edit by hand. `backup` is the file every case reads; each case is a device " +
                    "(profiles, domain rows, optional replica) and the user's choices. Ratings are 0..10 doubles; rows are " +
                    "listed sorted. The merge label for kept-both reviews is \"<deviceName> · yyyy-MM-dd\" (UTC) of exportedAt.",
            ),
            "backup" to obj(
                "manifestJson" to str(BackupManifestJson.encodeToString(BackupManifest.serializer(), backup.manifest)),
                "snapshotJson" to str(SyncJson.encodeToString(SyncEnvelope.serializer(), backup.snapshot)),
            ),
            "cases" to arr(cases),
        )
    }

