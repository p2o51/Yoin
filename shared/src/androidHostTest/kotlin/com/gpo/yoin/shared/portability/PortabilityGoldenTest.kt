            override suspend fun album(localProfileId: String?, provider: String, albumId: String) = knownAlbums
                .firstOrNull { it.profileId == localProfileId && it.provider == provider && it.albumId == albumId }
                ?.let { ReadableAlbum(it.name, it.artist) }

            override suspend fun track(localProfileId: String?, provider: String, trackId: String) = knownTracks
                .firstOrNull { it.profileId == localProfileId && it.provider == provider && it.trackId == trackId }
                ?.let { ReadableTrack(it.title, it.artist, it.albumId) }
        }
        val cases = listOf(Triple("en-UTC", "en", "UTC"), Triple("zh-Shanghai", "zh", "Asia/Shanghai"), Triple("en-NewYork", "en", "America/New_York"))
            .map { (name, language, zone) ->
                val content = BackupContent(snapshot, ExportFixture.accounts, ExportFixture.localProfiles, listOf("album_title"))
                val files = BackupExport.files(content, ExportFixture.source, names, ReadableLabels.forLanguage(language), zone)
                obj(
                    "name" to str(name),
                    "input" to obj("language" to str(language), "zoneId" to str(zone)),
                    "expected" to obj(
                        "fileName" to str(BackupFormat.fileName(snapshot.writtenAt, zone)),
                        "manifestJson" to str(files.manifestBytes.decodeToString()),
                        "snapshotJson" to str(files.snapshotBytes.decodeToString()),
                        "readable" to arr(files.readable.map { obj("path" to str(it.path), "text" to str(it.text)) }),
                    ),
                )
            }
        return obj(
            "about" to str(
                "Golden vectors for the backup export (manifest, snapshot, readable Markdown), generated from :shared " +
                    "Kotlin by PortabilityGoldenTest (androidHostTest). Do not edit by hand. Every case renders the same " +
                    "input with its own labels language and time zone.",
            ),
            "input" to obj(
                "snapshot" to Json.parseToJsonElement(ExportFixture.SNAPSHOT),
                "accounts" to Json.encodeToJsonElement(kotlinx.serialization.builtins.ListSerializer(BackupAccount.serializer()), ExportFixture.accounts),
                "localProfiles" to obj(*ExportFixture.localProfiles.map { (k, v) -> k to str(v) }.toTypedArray()),
