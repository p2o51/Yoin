            val store = FakeTransferStore().apply(case.seed)
            val before = storeJson(store)
            val caseItems = if (case.source.provider == "applemusic") appleItems else items
            val outcome = MemoryTransferApplier(store).apply(case.source, case.target, caseItems, case.tracks, case.albums, case.ledger) { 99_000 }
            obj(
                "name" to str(case.name),
                "input" to obj(
                    "source" to accountJson(case.source),
                    "target" to accountJson(case.target),
                    "items" to itemsJson(caseItems),
                    "tracks" to arr(case.tracks.map { obj("source" to str(it.source.toString()), "status" to str(it.status.name), "chosen" to (it.chosen?.let { t -> obj("provider" to str(t.provider), "id" to str(t.id), "title" to str(t.title), "artist" to str(t.artist), "albumProvider" to str(t.albumProvider), "albumId" to str(t.albumId)) } ?: JsonNull)) }),
                    "albums" to arr(case.albums.map { obj("source" to str(it.source.toString()), "status" to str(it.status.name), "chosen" to (it.chosen?.let { a -> obj("provider" to str(a.provider), "id" to str(a.id), "name" to str(a.name), "artist" to str(a.artist)) } ?: JsonNull)) }),
                    "ledger" to obj(*case.ledger.toSortedMap().map { (k, v) -> k to str(v) }.toTypedArray()),
                    "now" to num(99_000),
                    "target_rows" to before,
                ),
                "expected" to obj(
                    "result" to obj(
                        "copied" to transferCountsJson(outcome.result.copied),
                        "updated" to transferCountsJson(outcome.result.updated),
                        "kept" to transferCountsJson(outcome.result.kept),
                        "unmatched" to transferCountsJson(outcome.result.unmatched),
                        "reviewsJoined" to num(outcome.result.reviewsJoined),
                        "skippedPreviously" to num(outcome.result.skippedPreviously),
                    ),
                    "ledgerEntries" to obj(*outcome.ledgerEntries.map { (k, v) -> k to str(v) }.toTypedArray()),
                    "target_rows" to storeJson(store),
                ),
            )
        }
        val accounts = listOf(
            account("a", "s-a", "subsonic", "music.example.com"),
            account("b", "s-b", "subsonic", "MUSIC.example.com"),
