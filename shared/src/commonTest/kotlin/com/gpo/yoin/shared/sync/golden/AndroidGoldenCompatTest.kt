/**
 * The shared (iOS) sync against what Android's own code wrote ([ANDROID_SYNC_GOLDEN], generated by
 * app SyncGoldenFixtureTest). Runs on the JVM and on the iOS simulator (`:shared:allTests`).
 */
class AndroidGoldenCompatTest {
    private val golden = Json.parseToJsonElement(ANDROID_SYNC_GOLDEN).jsonObject
    private val deviceId = golden.str("deviceId")
    private val deviceName = golden.str("deviceName")
    private val writtenAt = golden["writtenAt"]!!.jsonPrimitive.long
    private val versionCode = golden["appVersionCode"]!!.jsonPrimitive.int
    private val scope = golden.str("scope")
    private val files = golden["files"]!!.jsonArray.map { it.jsonObject }

    private fun JsonObject.str(key: String) = this[key]!!.jsonPrimitive.content
    private fun JsonObject.strOrNull(key: String) = (this[key] as? JsonPrimitive)?.takeIf { it !is JsonNull }?.content
    private fun JsonObject.longOrNull(key: String) = (this[key] as? JsonPrimitive)?.longOrNull

    private fun records(json: String): List<JsonObject> =
        Json.parseToJsonElement(json).jsonObject["records"]!!.jsonArray.map { it.jsonObject }

    @Test
    fun should_reencodeAndroidFilesByteForByte_when_decodedByShared() {
        for (file in files) {
            val json = file.str("json")
            val envelope = SnapshotCodec.decode(json.encodeToByteArray())
            assertEquals(json, SyncJson.encodeToString(SyncEnvelope.serializer(), envelope))
            // Through gzip too (shared deflate, then inflate).
            val roundTrip = gunzipBytes(SnapshotCodec.encode(envelope)).decodeToString()
            assertEquals(json, roundTrip)
            val hash = CanonicalJson.hash(
                JsonArray(envelope.records.map { SyncJson.json.encodeToJsonElement(WireRecord.serializer(), it) }),
            )
            assertEquals(file.str("contentHash"), hash)
        }
    }

    private fun profile() = golden["profile"]!!.jsonObject.let { p ->
        SyncProfile(
            id = p.str("id"),
            provider = p.str("provider"),
            displayName = p.str("displayName"),
            createdAt = p["createdAt"]!!.jsonPrimitive.long,
            subsonicServerUrl = golden.str("serverUrl"),
            subsonicUsername = golden.str("username"),
        )
    }

    private fun seededDomain(profileId: String): FakeSyncDomain {
        val d = golden["domain"]!!.jsonObject
        val domain = FakeSyncDomain(golden.str("aboutLanguage"))
        for (n in d["notes"]!!.jsonArray.map { it.jsonObject }) {
            domain.putNote(
                SongNoteRow(n.str("id"), profileId, n.str("trackId"), n.str("provider"), n.str("content"),
                    n["createdAt"]!!.jsonPrimitive.long, n["updatedAt"]!!.jsonPrimitive.long, n.str("title"),
                    n.str("artist"), n.longOrNull("positionMs")),
            )
        }
        for (r in d["trackRatings"]!!.jsonArray.map { it.jsonObject }) {
            domain.putTrackRating(profileId, TrackRatingRow(r.str("provider"), r.str("songId"),
                r.str("rating").toDouble(), r["updatedAt"]!!.jsonPrimitive.long))
        }
        for (r in d["albumRatings"]!!.jsonArray.map { it.jsonObject }) {
            domain.putAlbumRating(profileId, AlbumRatingRow(r.str("provider"), r.str("albumId"),
                r.str("rating").toDouble(), r.strOrNull("review"), r.longOrNull("reviewUpdatedAt"),
                r["updatedAt"]!!.jsonPrimitive.long))
        }
        for (t in d["albumTitles"]!!.jsonArray.map { it.jsonObject }) {
            domain.putAlbumTitle(profileId, AlbumTitleRow(t.str("provider"), t.str("albumId"), t.str("title"),
                t["updatedAt"]!!.jsonPrimitive.long))
        }
        for (m in d["memoryCopies"]!!.jsonArray.map { it.jsonObject }) {
            domain.putMemoryCopy(profileId, MemoryCopyRow(m.str("provider"), m.str("entityType"), m.str("entityId"),
                m.str("copy"), m.str("promptHash"), m["generatedAt"]!!.jsonPrimitive.long, m.strOrNull("title"),
                m.strOrNull("titlePromptHash")))
        }
        for (a in d["songAbouts"]!!.jsonArray.map { it.jsonObject }) {
            domain.putSongAbout(SongAboutRow(a.str("titleKey"), a.str("artistKey"), a.str("albumKey"),
                a.str("titleDisplay"), a.str("artistDisplay"), a.str("albumDisplay"), a.str("kind"),
                a.str("entryKey"), a.strOrNull("promptText"), a.strOrNull("titleText"), a.str("answerText"),
                a["createdAt"]!!.jsonPrimitive.long, a["updatedAt"]!!.jsonPrimitive.long))
        }
        domain.profileList += profile().copy(id = profileId)
        return domain
    }

    private fun androidRecords(): List<JsonObject> = files.flatMap { records(it.str("json")) }

    @Test
    fun should_captureTheSameRecordsAsAndroid_when_holdingTheSameRows() = runTest {
        val store = InMemorySyncStore()
        val domain = seededDomain(profile().id)
        val binder = AccountBinder(store, { domain.profiles() }, clock = { writtenAt })
        val bindings = binder.refresh(emptyList())
        assertEquals(listOf(ActiveBinding(profile().id, scope, "subsonic")), bindings.active)
        val engine = SyncEngine(store, SharedSyncAdapters.create(domain, store), deviceId, { deviceName }, { writtenAt })

        engine.capture(bindings.active)
        val ours = engine.outgoingFiles(0L, writtenAt, versionCode).flatMap { file ->
            records(gunzipBytes(file.bytes).decodeToString())
        }

        // Android also writes kinds iOS has no adapter for (here: a setting); every other record is identical.
        val supported = SharedSyncAdapters.create(domain, store).map { it.kind }.toSet()
        val expected = androidRecords().filter { it.str("k") in supported }
        assertTrue(expected.size >= 15, "golden has ${expected.size} comparable records")
        assertEquals(expected.map { it.toString() }.sorted(), ours.map { it.toString() }.sorted())
    }

    @Test
    fun should_restoreAndroidDataAndRepublishItUnchanged_when_joiningAsAPeer() = runTest {
        val store = InMemorySyncStore()
        val domain = FakeSyncDomain(golden.str("aboutLanguage"))
        domain.profileList += profile().copy(id = "ios-subsonic", createdAt = writtenAt + 1)
        val engine = SyncEngine(store, SharedSyncAdapters.create(domain, store), "ios0000000000001", { "iPhone" }, {
            writtenAt + 60_000
        })
        for (file in files) {
            val remote = RemoteFile(
                id = file.str("name"), name = file.str("name"), version = 1, modifiedTime = null, size = null,
                appProperties = mapOf(SyncFileProps.KIND to file.str("fileKind"), SyncFileProps.DEVICE_ID to deviceId),
            )
            engine.mergeRemote(remote, SnapshotCodec.decode(file.str("json").encodeToByteArray()))
        }
        val bindings = AccountBinder(store, { domain.profiles() }, clock = { writtenAt }).refresh(emptyList())
        assertEquals(scope, bindings.active.single().syncProfileId)

        engine.capture(bindings.active)
        val applied = engine.apply(bindings.active)

        val seeded = seededDomain("ios-subsonic")
        assertEquals(seeded.notes, domain.notes)
        assertEquals(seeded.trackRatings, domain.trackRatings)
        assertEquals(seeded.albumRatings.values.map { it.copy(updatedAt = 0) },
            domain.albumRatings.values.map { it.copy(updatedAt = 0) })
        assertEquals(seeded.albumTitles.values.map { it.title }, domain.albumTitles.values.map { it.title })
        assertEquals(seeded.memories.values.toList(), domain.memories.values.toList())
        assertEquals(seeded.abouts.values.toList(), domain.abouts.values.toList())
        assertTrue(applied.totalApplied > 0)

        // A second local pass finds nothing new, and what this device publishes is Android's records, untouched
        // (its own account descriptor aside: it describes the account from this device too).
        engine.capture(bindings.active)
        val republished = engine.outgoingFiles(0L, writtenAt + 60_000, 1).flatMap { file ->
            records(gunzipBytes(file.bytes).decodeToString())
        }
        val notAccount = { r: JsonObject -> r.str("k") != SyncKinds.ACCOUNT }
        assertEquals(androidRecords().filter(notAccount).map { it.toString() }.sorted(),
            republished.filter(notAccount).map { it.toString() }.sorted())
        assertTrue(republished.any { it.str("k") == SyncKinds.SETTING }, "opaque Android setting carried")
    }
}
